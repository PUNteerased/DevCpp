"""Build single-file DevCpp-AI.exe with embedded Bloodshed Dev-C++ payload."""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BUILD = ROOT / "build"
DIST = ROOT / "dist"
PAYLOAD_ZIP = BUILD / "Dev-Cpp-payload.zip"
SPEC_DATAS_DIR = BUILD / "pyi_datas"
SECRETS = ROOT / "secrets.local.json"
EMBEDDED = ROOT / "src" / "devcpp_ai" / "_embedded_secrets.py"


def run(cmd: list[str]) -> None:
    print(">", " ".join(cmd))
    subprocess.check_call(cmd, cwd=str(ROOT))


def write_embedded_secrets() -> None:
    """Bake secrets.local.json into importable module for the frozen exe (gitignored)."""
    data: dict = {}
    if SECRETS.is_file():
        data = json.loads(SECRETS.read_text(encoding="utf-8"))
        print(f"Embedding secrets from {SECRETS.name}")
    else:
        print("WARNING: secrets.local.json missing — exe will have empty API key")

    api_key = json.dumps(str(data.get("api_key") or ""))
    base_url = json.dumps(str(data.get("base_url") or "https://api.dify.ai/v1"))
    ssid = json.dumps(str(data.get("hotspot_ssid") or "hah"))
    password = json.dumps(str(data.get("hotspot_password") or ""))
    allow_lan = "True" if data.get("allow_lan_fallback", True) else "False"
    EMBEDDED.write_text(
        "# Auto-generated by tools/build_exe.py — do not commit\n"
        f"API_KEY = {api_key}\n"
        f"BASE_URL = {base_url}\n"
        f"HOTSPOT_SSID = {ssid}\n"
        f"HOTSPOT_PASSWORD = {password}\n"
        f"ALLOW_LAN_FALLBACK = {allow_lan}\n",
        encoding="utf-8",
    )


def main() -> None:
    DIST.mkdir(parents=True, exist_ok=True)
    BUILD.mkdir(parents=True, exist_ok=True)

    write_embedded_secrets()

    if not PAYLOAD_ZIP.is_file():
        run([sys.executable, str(ROOT / "tools" / "pack_payload.py")])

    # Stage datas layout: payload/Dev-Cpp-payload.zip
    stage = SPEC_DATAS_DIR / "payload"
    stage.mkdir(parents=True, exist_ok=True)
    target = stage / "Dev-Cpp-payload.zip"
    if target.exists():
        target.unlink()
    target.write_bytes(PAYLOAD_ZIP.read_bytes())

    ico = ROOT / "source" / "orwelldevcpp" / "devcpp.ico"
    icon_args: list[str] = []
    if ico.is_file():
        icon_args = [f"--icon={ico}"]

    # Clean previous
    for p in DIST.glob("DevCpp-AI*"):
        if p.is_file():
            p.unlink()

    sep = ";"  # Windows PyInstaller path separator for --add-data
    add_data = f"{stage}{sep}payload"

    cmd = [
        sys.executable,
        "-m",
        "PyInstaller",
        "--noconfirm",
        "--clean",
        "--onefile",
        "--windowed",
        "--name",
        "DevCpp-AI",
        "--paths",
        str(ROOT / "src"),
        "--hidden-import",
        "devcpp_ai",
        "--hidden-import",
        "devcpp_ai.app",
        "--hidden-import",
        "devcpp_ai.chat_ui",
        "--hidden-import",
        "devcpp_ai.llm",
        "--hidden-import",
        "devcpp_ai.network",
        "--hidden-import",
        "devcpp_ai.install",
        "--hidden-import",
        "devcpp_ai.uninstall",
        "--hidden-import",
        "devcpp_ai.config",
        "--hidden-import",
        "devcpp_ai.markdown_view",
        "--hidden-import",
        "devcpp_ai._embedded_secrets",
        "--add-data",
        add_data,
        *icon_args,
        str(ROOT / "src" / "run_devcpp_ai.py"),
    ]
    run(cmd)

    exe = DIST / "DevCpp-AI.exe"
    if not exe.is_file():
        # PyInstaller may put under dist/
        raise SystemExit("Build failed: DevCpp-AI.exe not found in dist/")
    mb = exe.stat().st_size / (1024 * 1024)
    print(f"OK: {exe} ({mb:.1f} MB)")


if __name__ == "__main__":
    main()
